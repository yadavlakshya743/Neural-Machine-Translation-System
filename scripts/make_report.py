#!/usr/bin/env python3
"""Builds experiments/evaluation_report.md from every run in models/.

Reads metrics.json (training/dev history), eval_test_*.json (test scores) and the
hypotheses files written by scripts/evaluate.py, then adds:
  * baseline-vs-final and greedy-vs-beam comparisons,
  * BLEU/chrF++ by source-length bucket,
  * automatic error analysis (repetition, untranslated script, length problems, empty
    output) with best/worst examples by sentence-level chrF++.

Usage:  python scripts/make_report.py [--models_dir models] [--out experiments/evaluation_report.md]
"""

import argparse
import glob
import json
import os
import re
import sys
from collections import Counter

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from sacrebleu.metrics import BLEU, CHRF  # noqa: E402

DEVANAGARI = re.compile(r"[ऀ-ॿ]")
LATIN_WORD = re.compile(r"\b[A-Za-z]{3,}\b")
BUCKETS = [(0, 10, "1-10 words"), (10, 20, "11-20"), (20, 40, "21-40"), (40, 10_000, "41+")]


def read_lines(path):
    with open(path, encoding="utf-8") as f:
        return [l.rstrip("\n") for l in f]


def has_repetition(text):
    toks = text.split()
    return any(toks[i] == toks[i + 1] and len(toks[i]) > 1 for i in range(len(toks) - 1))


def untranslated(text, tgt_lang):
    if tgt_lang == "hi":
        return bool(LATIN_WORD.search(text))
    return bool(DEVANAGARI.search(text))


def analyse(sources, refs, hyps, tgt_lang):
    chrf = CHRF(word_order=2)
    n = len(hyps)
    flags = Counter()
    scored = []
    for s, r, h in zip(sources, refs, hyps):
        ratio = len(h.split()) / max(1, len(r.split()))
        f = {
            "empty output": not h.strip(),
            "repeated word": has_repetition(h),
            f"untranslated {'Latin' if tgt_lang == 'hi' else 'Devanagari'} text": untranslated(h, tgt_lang),
            "too short (<60% of reference length)": ratio < 0.6,
            "too long (>150% of reference length)": ratio > 1.5,
        }
        for k, v in f.items():
            flags[k] += int(v)
        scored.append((chrf.sentence_score(h, [r]).score, s, r, h))
    scored.sort(key=lambda x: x[0])

    buckets = []
    for lo, hi, label in BUCKETS:
        idx = [i for i, s in enumerate(sources) if lo < len(s.split()) <= hi or (lo == 0 and len(s.split()) <= hi)]
        if not idx:
            continue
        h = [hyps[i] for i in idx]
        r = [[refs[i] for i in idx]]
        buckets.append((label, len(idx), BLEU(force=True).corpus_score(h, r).score, CHRF(word_order=2).corpus_score(h, r).score))
    return {"n": n, "flags": flags, "worst": scored[:4], "best": scored[-3:][::-1], "buckets": buckets}


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--models_dir", default="models")
    p.add_argument("--processed_dir", default="data/processed")
    p.add_argument("--out", default="experiments/evaluation_report.md")
    p.add_argument("--include_smoke", action="store_true")
    args = p.parse_args()

    runs = []
    for mpath in sorted(glob.glob(os.path.join(args.models_dir, "*", "metrics.json"))):
        run_dir = os.path.dirname(mpath)
        if os.path.basename(run_dir).startswith("smoke") and not args.include_smoke:
            continue
        data = json.load(open(mpath, encoding="utf-8"))
        evals = [json.load(open(e, encoding="utf-8")) for e in sorted(glob.glob(os.path.join(run_dir, "eval_test_*.json")))]
        runs.append((run_dir, data, evals))
    if not runs:
        sys.exit("No runs with metrics.json found.")

    L = ["# Evaluation Report: English ↔ Hindi Transformer NMT", "",
         "Generated by `scripts/make_report.py` from the saved training metrics and test-set evaluations. "
         "All test scores use the **official IIT Bombay test split** (2,507 sentences), which was never used "
         "for training or model selection (model selection used dev BLEU). BLEU and chrF++ are computed with "
         "sacreBLEU; signatures are listed below. Automatic metrics measure overlap with one reference "
         "translation and do not prove semantic correctness.", ""]

    # ---- Summary table
    rows = []
    for run_dir, data, evals in runs:
        meta, st = data["meta"], data["state"]
        mc = meta.get("config", {}).get("model", {})
        best = {e["decoding"]["strategy"]: e for e in evals}
        g, b = best.get("greedy"), best.get("beam_search")
        rows.append([
            f"`{meta['run_name']}`", meta["direction"],
            f"{meta.get('total_parameters', 0) / 1e6:.1f}M (d{mc.get('d_model')}, {mc.get('n_encoder_layers')}+{mc.get('n_decoder_layers')}L)",
            len(st["history"]["epochs"]), f"{st['elapsed_sec'] / 3600:.1f} h",
            f"{st.get('best_score')}",
            f"{g['metrics']['bleu']} / {g['metrics']['chrf2']}" if g else "—",
            f"{b['metrics']['bleu']} / {b['metrics']['chrf2']}" if b else "—",
        ])
    L += ["## 1. Results summary", "",
          md_table(["Run", "Direction", "Model", "Epochs", "Train time", "Best dev BLEU",
                    "Test BLEU / chrF++ (greedy)", "Test BLEU / chrF++ (beam k=4)"], rows), ""]

    targets = {"en-hi": (20, 45), "hi-en": (22, 50)}
    L += ["PRD minimum targets: EN→HI BLEU ≥ 20, chrF++ ≥ 45; HI→EN BLEU ≥ 22, chrF++ ≥ 50.", ""]

    # ---- Per run details
    for run_dir, data, evals in runs:
        meta, st, tc = data["meta"], data["state"], data["train_config"]
        src, tgt = meta["src_lang"], meta["tgt_lang"]
        L += [f"## {meta['run_name']} ({src.upper()} → {tgt.upper()})", "",
              f"- Training pairs: {meta.get('train_pairs', 0):,}; parameters: {meta.get('total_parameters', 0):,}",
              f"- Optimizer: AdamW, peak LR {tc.get('learning_rate')}, warmup {tc.get('warmup_steps')} steps, "
              f"label smoothing {tc.get('label_smoothing')}, accumulation {tc.get('accum_steps')}, mixed precision {tc.get('use_amp')}",
              f"- Status: {st['status']} after {st['global_step']:,} optimizer steps ({st['elapsed_sec'] / 3600:.1f} h)", "",
              "### Learning curve (dev set, after each epoch)", "",
              md_table(["Epoch", "Step", "Dev loss", "Dev BLEU", "Dev chrF++", "Best"],
                       [[e["epoch"], f"{e['step']:,}", e["val_loss"], e.get("dev_bleu"), e.get("dev_chrf2"),
                         "✓" if e.get("best") else ""] for e in st["history"]["epochs"]]), ""]
        if not evals:
            L += ["_No test-set evaluation yet. Run `scripts/evaluate.py` on this run's best.pt._", ""]
            continue

        L += ["### Test set: greedy vs beam search", "",
              md_table(["Decoding", "BLEU", "chrF++", "ms / sentence"],
                       [[e["decoding"]["strategy"] + (f" k={e['decoding']['beam_size']}" if e["decoding"]["strategy"] == "beam_search" else ""),
                         e["metrics"]["bleu"], e["metrics"]["chrf2"], e["performance"]["ms_per_sentence"]] for e in evals]), "",
              f"Signatures: `{evals[0]['metrics']['bleu_signature']}` · `{evals[0]['metrics']['chrf2_signature']}`", ""]

        best_eval = max(evals, key=lambda e: e["metrics"]["bleu"])
        strat = best_eval["decoding"]["strategy"]
        hyp_glob = glob.glob(os.path.join(run_dir, f"hyp_test_{strat}*.{tgt}.txt"))
        if not hyp_glob:
            continue
        hyps = read_lines(hyp_glob[0])
        sources = read_lines(os.path.join(args.processed_dir, f"test_{src}.txt"))[: len(hyps)]
        refs = read_lines(os.path.join(args.processed_dir, f"test_{tgt}.txt"))[: len(hyps)]
        a = analyse(sources, refs, hyps, tgt)

        L += [f"### Quality by source length ({strat})", "",
              md_table(["Source length", "Sentences", "BLEU", "chrF++"],
                       [[lab, n, f"{bl:.2f}", f"{ch:.2f}"] for lab, n, bl, ch in a["buckets"]]), "",
              f"### Error analysis ({strat}, {a['n']:,} test sentences, automatic heuristics)", "",
              md_table(["Pattern", "Sentences", "Share"],
                       [[k, v, f"{100 * v / a['n']:.1f}%"] for k, v in a["flags"].most_common()]), "",
              "Heuristics flag symptoms, not causes; a human should review the examples below.", "",
              "**Lowest-scoring examples (sentence chrF++):**", ""]
        for score, s, r, h in a["worst"]:
            L += [f"- chrF++ {score:.1f}", f"  - SRC: {s}", f"  - REF: {r}", f"  - HYP: {h}"]
        L += ["", "**Highest-scoring examples:**", ""]
        for score, s, r, h in a["best"]:
            L += [f"- chrF++ {score:.1f}", f"  - SRC: {s}", f"  - REF: {r}", f"  - HYP: {h}"]
        L += [""]

    L += ["## Methodology notes", "",
          "- Data: IIT Bombay corpus, official split. Training data was cleaned (normalization, length/ratio "
          "filters), deduplicated, and any sentence appearing in dev/test was removed (leakage control).",
          "- Model selection: the checkpoint with the best **dev** BLEU (greedy) is kept as `best.pt`; "
          "the test set is only used for the final numbers in this report.",
          "- Decoding: greedy vs beam search (k=4, length penalty α=0.6, Wu et al. 2016).",
          "- Limitations: single reference per sentence; BLEU underestimates valid paraphrases, especially for "
          "Hindi word order and morphology (chrF++ is more forgiving at the character level).", ""]

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print(f"[+] Wrote {args.out}")


if __name__ == "__main__":
    main()
